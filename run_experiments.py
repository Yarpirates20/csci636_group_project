#Tries each grid setting with TimeSeriesSplit
# each fold trains on past and tests on next, one-day gap to avoid look-ahead bias
# avgs AUC across folds, picks best setting
def walk_forward_select(builder, grid, X, y):
    #builder: function that takes hyperparams and returns a fitted model
    #grid: list of hyperparam dicts to try
    tscv = TimeSeriesSplit(n_splits=CV_SPLITS, gap=1)
    best = (None, -np.inf)
    #Iterate over each hyperparameter setting in the grid
    # walk-forward cross-validation, compute the avg AUC for each setting,
    # track best hyperparam setting based on the highest average AUC
    for params in grid:
        aucs = []
        #Iterate over each train-test split generated by TimeSeriesSplit
        for tr, va in tscv.split(X):
            m = builder(**params).fit(X.iloc[tr], y.iloc[tr]) #fit the model on the training data for the current split
            aucs.append(roc_auc_score(y.iloc[va], m.predict_proba(X.iloc[va])[:, 1])) #compute the AUC on the validation data
        #If the average AUC for current hyperparam is better update the best setting and corresponding AUC
        if np.mean(aucs) > best[1]:
            best = (params, float(np.mean(aucs)))
    return best

#Writes mean |SHAP| per feature to CSV (no plotting)
def save_shap_importance(rf, X, name):
    #Tries to compute SHAP values for the Random Forest model and save the mean absolute SHAP values per feature to a CSV
    #If error occurs,  prints a message and skips the SHAP computation
    try:
        import shap
        sv = shap.TreeExplainer(rf).shap_values(X)
        #If the SHAP values are a list (for multi-class classification), take the second element (class 1)
        if isinstance(sv, list):
            sv = sv[1]
        #If the SHAP values are a 3D array (for multi-output models), take the second output (class 1)
        elif getattr(sv, "ndim", 2) == 3:
            sv = sv[:, :, 1]
        #Compute the mean absolute SHAP values for each feature, sort in desc, and save to CSV
        imp = pd.Series(np.abs(sv).mean(axis=0), index=X.columns).sort_values(ascending=False)
        imp.rename("mean_abs_shap").to_csv(REPORTS / f"shap_importance_{name}.csv")
    except Exception as e:
        print(f"SHAP skipped for {name}: {e}")

#Initialize lists and dictionaries to store results
rows, curves, probs_out = [], {}, {}
#Iterate over each dataset (baseline, enhanced) to train and evaluate models
for kind in ["baseline", "enhanced"]:
    print(f"\n----- {kind} Dataset -----")
    #Load the features (X) and target (y) for train, validation, and test splits
    Xtr, ytr = load_xy(kind, "train")
    Xva, yva = load_xy(kind, "validation")
    Xte, yte = load_xy(kind, "test") if FINAL else (None, None)
    Xtv, ytv = pd.concat([Xtr, Xva]), pd.concat([ytr, yva])

    #LSTM: fit on train, early-stop on validation, predict on eval
    if FINAL: #fit on 2018-2025, score on 2026
        fitX, fity, evalX, evaly = Xtv, ytv, Xte, yte
        lstm_tr = (Xtr, ytr); lstm_es = (Xva, yva); hist = Xtv
    else: #fit on 2018-2024, score on 2025
        fitX, fity, evalX, evaly = Xtr, ytr, Xva, yva
        lstm_tr = (Xtr.iloc[:-365], ytr.iloc[:-365]); lstm_es = (Xtr.iloc[-365:], ytr.iloc[-365:]); hist = Xtr

    #LogReg & RF: select via walk-forward CV then refit on all fit data
    lr_p, lr_auc = walk_forward_select(build_logreg, LOGREG_GRID, fitX, fity)
    rf_p, rf_auc = walk_forward_select(build_rf, RF_GRID, fitX, fity)
    #print("LogReg", lr_p, round(lr_auc, 3), "| RF", rf_p, round(rf_auc, 3))
    print(f"\n{kind.upper()} dataset: model scores (AUC; 0.50 = coin flip, 1.0 = perfect)")
    print(f"  Logistic regression: {lr_auc:.3f}   (settings chosen: C={lr_p['C']})")
    print(f"  Random forest:       {rf_auc:.3f}   (settings chosen: depth={rf_p['max_depth']}, leaf={rf_p['min_samples_leaf']})")
    lr = build_logreg(**lr_p).fit(fitX, fity)
    rf = build_rf(**rf_p).fit(fitX, fity)

    #LSTM
    lstm = TorchLSTM().fit(*lstm_tr, *lstm_es)
    pv = lstm.predict_proba(lstm_es[0], history=lstm_tr[0]) #predict probabilities on the eval set
    lstm_auc = roc_auc_score(lstm_es[1].loc[pv.index], pv) #compute AUC on the eval set
    print("LSTM early-stop-set AUC", round(lstm_auc, 3))

    #Evaluation-set predictions
    #Predict probabilities for each model on the eval set
    P = {"LogReg": pd.Series(lr.predict_proba(evalX)[:, 1], index=evalX.index),
         "RandForest": pd.Series(rf.predict_proba(evalX)[:, 1], index=evalX.index),
         "LSTM": lstm.predict_proba(evalX, history=hist)}
    #Weighted ensemble: weights proportional to AUC above 0.5, else equal weights
    w = np.array([max(a - 0.5, 0) for a in (lr_auc, rf_auc, lstm_auc)])
    w = w / w.sum() if w.sum() > 0 else np.ones(3) / 3
    print("Ensemble weights (LR, RF, LSTM):", w.round(2))
    #Compute the weighted ensemble probabilities
    P["Ensemble"] = w[0] * P["LogReg"] + w[1] * P["RandForest"] + w[2] * P["LSTM"]

    #Buy&Hold next-day returns for comparison
    bh = next_ret.reindex(evalX.index).dropna()
    #Save the predicted probabilities for each model on the eval set to a DataFrame and store it in probs_out
    probs_out[kind] = pd.DataFrame(P)
    #Compute performance metrics for each model and store the results in rows and curves
    for name, p in P.items():
        y_true = evaly.loc[p.index] #get labels corresponding to the predicted probabilities
        pred = (p > THRESHOLD).astype(int) #convert probabilities to binary predictions based on the threshold
        strat = backtest(p, next_ret) #compute the daily strategy returns
        #Store the performance metrics for each model in rows and curves
        rows.append({"dataset": kind, "model": name,
                     "acc": accuracy_score(y_true, pred), "f1": f1_score(y_true, pred),
                     "auc": roc_auc_score(y_true, p), **perf(strat, bh)})
        curves[(kind, name)] = strat
    #Store the Buy&Hold returns in curves for comparison and  SHAP importance for the Random Forest model
    curves[(kind, "BuyHold")] = bh
    save_shap_importance(rf, evalX, f"{kind}_{TAG}")

#Final results: save CSVs, print summary
